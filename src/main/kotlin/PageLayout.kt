/**
 * A mark captured from the input stream together with its content, the
 * nested marks and the text, to be [replay]ed at another place of the output.
 */
private class CapturedMark(val mark: SemanticEvent.Mark) {
    val content = mutableListOf<Any>() // CapturedMark or String
}

/**
 * Emits the [captured] mark and its content as they came in,
 * keeping the [SemanticEvent.Mark.isTagged] flag.
 */
private suspend fun MatcherScope.replay(captured: CapturedMark) {
    val block: suspend MatcherScope.() -> Unit = {
        captured.content.forEach {
            if (it is CapturedMark) replay(it) else +(it as String)
        }
    }
    val mark = captured.mark
    if (mark.isTagged) tag(mark.name, mark.attributes, block)
    else mark.name(mark.attributes, block)
}

/**
 * Applies the xemantic.com page layout: the `head` is completed with
 * `charset`/`viewport` metas, the [BEER_CSS] and the xemantic.com
 * stylesheets, the [PRELOADED_FONTS] preloads, and the scripts rendering
 * the background shader, preloaded as well, the `body` content is prefixed with the
 * [COLOR_SCHEME_INIT_JS] and a top app bar (`header.fixed` with a `section.responsive` holding the `nav`),
 * its content as wide as the one of `main` and carrying the [MENU], the `body` content is wrapped
 * in BeerCSS's `main.responsive` container, followed by the [MENU_DRAWER]
 * holding the same [MENU] for smaller screens, the table of contents, if
 * there is one (the `nav#toc`
 * appended by `wrapInSections` at the very end of the content), is moved
 * out of `main`, following it, below the [pageActions] of the [page], in the [TOC_DRAWER], toggled by the button
 * in the corner of the top app bar, whose navigation ends with the color scheme switch, and copied to the [MENU_DRAWER], and
 * the `body` is closed with a `footer` holding the logo, the site map
 * of the [footer] groups, read by [readSiteFooter], the [COPYRIGHT]
 * notice, and the colophon of the [footer].
 */
fun Flow<SemanticEvent>.applyPageLayout(
    page: Page,
    footer: SiteFooter
) = transform {

    // the nav#toc of wrapInSections, captured instead of emitted in place,
    // and replayed by the body after main
    var toc: CapturedMark? = null
    val captured = mutableListOf<CapturedMark>()
    // the `toc` entry of the front matter, see TOC_DRAWER
    var tocClosed = false

    // not a metadata of the page, hence dropped from the head
    match({ name == "meta" && this["name"] == "toc" }) { mark ->
        check(mark["content"] == TOC_CLOSED) {
            "${page.path} sets `toc: ${mark["content"]}` in its front matter, the only value supported is `$TOC_CLOSED`"
        }
        tocClosed = true
    }

    match("head") {
        "head" {
            "meta"("charset" to "utf-8") {}
            "meta"(
                "name" to "viewport",
                "content" to "width=device-width, initial-scale=1"
            ) {}
            children()
            // the favicon.ico at the site root is found by convention, but only
            // a link lets the browser prefer the vector one
            "link"("rel" to "icon", "href" to FAVICON_ICO, "sizes" to "48x48") {}
            "link"("rel" to "icon", "href" to FAVICON_SVG, "type" to "image/svg+xml") {}
            "link"("rel" to "apple-touch-icon", "href" to APPLE_TOUCH_ICON) {}
            "link"("href" to BEER_CSS, "rel" to "stylesheet") {}
            "link"("href" to XEMANTIC_CSS, "rel" to "stylesheet") {}
            "script"("src" to PAGE_ACTIONS_JS, "defer" to "") {}
            "script"("src" to COLOR_SCHEME_JS, "defer" to "") {}
            "script"("src" to SHADER_WEB_BACKGROUND_JS, "defer" to "") {}
            "script"("src" to GENERATIVE_ART_DECO_JS, "defer" to "") {}
            "link"(
                "href" to GENERATIVE_ART_DECO_SHADER,
                "rel" to "preload",
                "as" to "fetch",
                "crossorigin" to "anonymous"
            ) {}
            PRELOADED_FONTS.forEach { font ->
                "link"(
                    "href" to font,
                    "rel" to "preload",
                    "as" to "font",
                    "type" to "font/woff2",
                    "crossorigin" to "anonymous"
                ) {}
            }
        }
    }

    match("body") {
        "body" {
            "script"("src" to COLOR_SCHEME_INIT_JS) {}
            // the bar spans the viewport, while its content is as wide as the one
            // of main: BeerCSS limits the width of a .responsive main, header,
            // footer or section only, not of a nav; xemantic.css aligns the paddings
            "header"("class" to "fixed $TINTED_GLASS") {
                "section"("class" to "responsive") {
                    "nav" {
                        "button"(
                            "class" to "circle transparent s m",
                            "popovertarget" to MENU_DRAWER,
                            "aria-label" to "Menu"
                        ) {
                            "i" { +"menu" }
                        }
                        // centered between two spacers where the menu button is
                        // shown (BeerCSS's `s` and `m` helpers), as the only other
                        // element of the bar, the color scheme switch, is as wide
                        "div"("class" to "max s m") {}
                        logoLink("header-logo")
                        "div"("class" to "max") {}
                        MENU.forEach { item ->
                            "a"("href" to item.href, "class" to "button transparent l") {
                                +item.label
                            }
                        }
                        // on large screens only (BeerCSS's `l` helper), on the
                        // smaller ones it is in the MENU_DRAWER
                        "a"(
                            "href" to GITHUB_URL,
                            "class" to "circle transparent wave l",
                            "aria-label" to "Xemantic on GitHub"
                        ) {
                            "span"("class" to "brand-icon github") {}
                        }
                        // xemantic.css shows the icon of the scheme to switch to
                        "button"(
                            "class" to "circle transparent color-scheme-toggle",
                            "data-toggle-color-scheme" to "",
                            "aria-label" to "Switch between dark and light mode"
                        ) {
                            "i"("class" to "to-light") { +"light_mode" }
                            "i"("class" to "to-dark") { +"dark_mode" }
                        }
                    }
                }
                // in the very top left corner, out of the section, which it
                // follows, as BeerCSS adds a margin to a section following a sibling, on large screens only (BeerCSS's `l` helper)
                "button"(
                    "class" to "circle transparent toc-toggle l",
                    "popovertarget" to TOC_DRAWER,
                    "aria-label" to "Table of contents"
                ) {
                    "i" { +"toc" }
                }
            }
            "main"("class" to "responsive") {
                children(mode = MAIN_CONTENT)
            }
            // the drawers follow main, as both hold the table of contents,
            // captured only once the content has streamed
            defer {
                "dialog"(
                    "id" to MENU_DRAWER,
                    "class" to "left $TINTED_GLASS",
                    "popover" to "",
                    "aria-label" to "Site navigation"
                ) {
                    "header" {
                        "nav" {
                            "button"(
                                "class" to "circle transparent",
                                "popovertarget" to MENU_DRAWER,
                                "popovertargetaction" to "hide",
                                "aria-label" to "Close menu"
                            ) {
                                "i" { +"menu_open" }
                            }
                            logoLink("drawer-logo")
                        }
                    }
                    "ul"("class" to "list") {
                        val pagePath = page.path.htmlPagePath()
                        MENU.forEach { item ->
                            // BeerCSS has no active list item, only an active
                            // link, whose icon it fills: xemantic.css adds the rest
                            val current = item.ariaCurrent(pagePath)
                            val attributes = buildList {
                                add("href" to item.href)
                                if (current != null) {
                                    add("class" to "active")
                                    add("aria-current" to current)
                                }
                            }
                            "li"("class" to "wave round") {
                                "a"(*attributes.toTypedArray()) {
                                    "i" { +item.icon }
                                    "span" { +item.label }
                                }
                            }
                        }
                        // in the top app bar on large screens only
                        "li"("class" to "wave round") {
                            "a"("href" to GITHUB_URL) {
                                "span"("class" to "brand-icon github") {}
                                "span" { +"GitHub" }
                            }
                        }
                    }
                    // on the screens of this drawer it is the only place of
                    // the page actions, xemantic.css hides those following the h1
                    "hr" {}
                    drawerPageActions(page.markdownPath())
                    // and of the table of contents, see the TOC_DRAWER
                    toc?.let { toc ->
                        "hr" {}
                        "nav"("class" to "toc", "aria-label" to "Table of contents") {
                            toc.content.forEach {
                                if (it is CapturedMark) replay(it) else +(it as String)
                            }
                        }
                    }
                }
                // on large screens only (BeerCSS's `l` helper), like its toggle;
                // without a table of contents it holds the page actions alone,
                // and stays closed until toggled
                "dialog"(
                    "id" to TOC_DRAWER,
                    "class" to "left $TINTED_GLASS l",
                    "popover" to "",
                    "aria-label" to if (toc != null) "Table of contents" else "Page actions",
                    "data-default" to if (tocClosed || toc == null) TOC_CLOSED else "open"
                ) {
                    // staying at the top of the drawer, as only the table of
                    // contents scrolls
                    pageActions(page.markdownPath())
                    toc?.let { replay(it) }
                }
                "script"("src" to TOC_DRAWER_JS) {}
            }
            "footer"("class" to TINTED_GLASS) {
                "section"("class" to "responsive site-footer") {
                    logoLink("site-footer-logo")
                    "nav"("class" to "site-footer-groups", "aria-label" to "Site map") {
                        footer.groups.forEach { group ->
                            "div" {
                                "h2" {
                                    val href = group.href
                                    if (href != null) {
                                        "a"("href" to href) { +group.title }
                                    } else {
                                        +group.title
                                    }
                                }
                                "ul" {
                                    group.links.forEach { link ->
                                        "li" {
                                            "a"("href" to link.href) { +link.label }
                                            link.note?.let { note ->
                                                +" "
                                                "span"("class" to "site-footer-note") { +note }
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }
                    newsletterForm()
                    "div"("class" to "site-footer-legal") {
                        "p" {
                            +"$COPYRIGHT · Content licensed under "
                            "a"("href" to CONTENT_LICENSE_URL, "rel" to "license") {
                                +CONTENT_LICENSE
                            }
                            +" unless stated otherwise"
                        }
                        "div"("class" to "site-footer-social") {
                            SOCIAL_LINKS.forEach { link ->
                                "a"(
                                    "href" to link.href,
                                    "class" to "circle transparent wave",
                                    "aria-label" to "Xemantic on ${link.name}",
                                    "title" to link.name
                                ) {
                                    "span"("class" to "brand-icon ${brandIcon(link.href)}") {}
                                }
                            }
                        }
                    }
                    if (footer.colophon.isNotEmpty()) {
                        // a div rather than a p, which BeerCSS would push down by a 1rem margin
                        "div"("class" to "site-footer-colophon") {
                            footer.colophon.forEach { piece ->
                                val href = piece.href
                                if (href != null) {
                                    "a"("href" to href) { +piece.text }
                                } else {
                                    +piece.text
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    match({ name == "nav" && this["id"] == "toc" }) { mark ->
        val nav = CapturedMark(mark)
        toc = nav
        captured += nav
        children(mode = "capture")
        afterClose { captured.removeLast() }
    }

    match("*", mode = "capture") { mark ->
        val child = CapturedMark(mark)
        captured.last().content += child
        captured += child
        children(mode = "capture")
        afterClose { captured.removeLast() }
    }

    matchText(mode = "capture") {
        captured.last().content += it
    }

    var titleScriptAdded = false
    // of the top level sections only the profile of a person is a glass panel
    match({ name == "section" && hasClass(PROFILE_SECTION) }, mode = MAIN_CONTENT) { mark ->
        "section"(mark.attributes + ("class" to "${mark["class"]} $TINTED_GLASS")) {
            children()
        }
    }

    match("h1") { mark ->
        mark.name(mark.attributes) {
            children()
        }
        if (!titleScriptAdded) {
            titleScriptAdded = true
            // not deferred: it runs right after the title, before the first paint
            "script"("src" to TITLE_JS) {}
        }
    }

    passthrough()

}
